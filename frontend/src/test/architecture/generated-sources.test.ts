import { describe, expect, it } from 'vitest'
import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import { buildImportGraph, isGeneratedSource, relativeTo } from './import-graph'

const FRONTEND_SRC = path.resolve(__dirname, '../..')

function withTempFile<T>(name: string, contents: string, run: (file: string) => T): T {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'generated-src-'))
  const file = path.join(dir, name)
  fs.writeFileSync(file, contents)
  try {
    return run(file)
  } finally {
    fs.rmSync(dir, { recursive: true, force: true })
  }
}

/**
 * The scanner used to walk `api/opencode-types.ts` - 6802 generated lines,
 * about a tenth of the frontend - as if it were hand-written, and the cost was
 * measurable: `i18n.test.ts` records that widening its expression reports 95
 * false positives because that file is full of SSE event names sharing a
 * namespace with the locale files.
 *
 * Excluding it by path is what that file rejected, and rightly: the problem is
 * not this one path, it is that a rule about hand-written code should not be
 * applied to code nobody wrote. So the file is asked instead - a header that
 * declares the file generated removes it from every rule at once, and the next
 * generated file needs nothing added to any list.
 *
 * The rules below exist because an exclusion that stops matching is the quiet
 * kind of regression: nothing turns red, the generated file simply rejoins the
 * scan set and the i18n false positives come back with it.
 */
describe('生成文件不参与手写代码的规则', () => {
  it('门禁自己看得见东西', () => {
    const graph = buildImportGraph(FRONTEND_SRC, [['@', FRONTEND_SRC]])
    expect(graph.files.length, '源文件少得可疑，这门禁多半跑在空集上').toBeGreaterThan(100)
    expect(
      graph.files.some((file) => file.endsWith('opencode-types.ts')),
      'opencode-types.ts 回到了扫描集里，批次 1a 等于没做',
    ).toBe(false)
    expect(
      graph.files.some((file) => relativeTo(graph, file) === 'App.tsx'),
      '连入口都不在扫描集里，这条规则正在空跑',
    ).toBe(true)
  })

  it('认得出自述为生成的文件', () => {
    // Spelled differently from the real file's notice on purpose: a detector
    // that only matched the exact wording would pass here and fail in anger.
    const cases: [string, string][] = [
      ['// @generated by some-tool - do not edit', 'marker as a line comment'],
      ['/**\n * Code generated by protoc. DO NOT EDIT.\n */', 'marker in a block comment'],
      ['// automatically generated - all changes will be lost', 'automatic wording'],
    ]
    for (const [header, why] of cases) {
      const detected = withTempFile('sample.ts', `${header}\nexport const x = 1\n`, isGeneratedSource)
      expect(detected, `没认出来：${why}`).toBe(true)
    }
  })

  it('认不出普通的手写文件', () => {
    const handwritten = [
      "import type { A } from './a'\n",
      '/**\n * A helper that reads generated output.\n */\nexport const read = () => 1\n',
    ]
    for (const [index, contents] of handwritten.entries()) {
      const detected = withTempFile(`hand-${index}.ts`, contents, isGeneratedSource)
      expect(detected, `把一份手写文件判成了生成文件（第 ${index + 1} 份）`).toBe(false)
    }
  })

  it('声明写在正文里不算数', () => {
    // The buried marker has to be one the detector actually keys on, or this
    // rule passes whether or not the header limit does anything. 009-prompt-
    // templates.ts carries 'Do not edit files.' inside a SQL literal at line
    // 103 - reading the whole file would classify a hand-written migration as
    // generated and quietly drop it out of every rule.
    const buried = [
      ...Array.from({ length: 100 }, (_, i) => `const filler${i} = ${i}`),
      'const note = "// @generated - this string is data, not a header"',
    ].join('\n')
    const detected = withTempFile('buried.ts', buried, isGeneratedSource)
    expect(detected, '只读文件头，却被正文里的一句话带走了').toBe(false)
  })
})
